"""Finite identity diagnostics vocabulary shared by policy and metadata tracing."""

IDENTITY_REASONS = frozenset(
    "FACE_TOO_SMALL LANDMARKS_INVALID FACE_CROP_EMPTY FACE_BLURRED FACE_EXPOSURE "
    "SCENE_TOO_DARK SCENE_EXPOSURE_FAILURE FACE_ASSOCIATION_AMBIGUOUS CAPACITY_EXCEEDED "
    "EMPTY_GALLERY NO_FACE NOT_CHECKED MATCH_SCORE_AMBIGUOUS MATCH_MARGIN_AMBIGUOUS "
    "IDENTITY_CONFLICT INSUFFICIENT_IDENTITY_EVIDENCE IDENTITY_EVIDENCE_EXPIRED "
    "IDENTITY_EVIDENCE_CONFLICT OTHER".split()
)
IDENTITY_DECISIONS = frozenset("KNOWN UNKNOWN UNCERTAIN NO_FACE NOT_CHECKED".split())


def identity_reason(value):
    return value if value in IDENTITY_REASONS else "OTHER" if value else None
